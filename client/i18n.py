def get_configured_language_setting() -> str:
    """Reads configured language code ('auto', 'es', 'en') from QSettings."""
    settings = QSettings("FocusGuard", "FocusGuardTray")
    return settings.value("language", "auto")


def set_configured_language_setting(lang_code: str) -> None:
    """Saves configured language code ('auto', 'es', 'en') to QSettings."""
    settings = QSettings("FocusGuard", "FocusGuardTray")
    settings.setValue("language", lang_code)


def resolve_active_language() -> str:
    """
    Resolves effective language ('es' or 'en').
    If configured to 'auto', inspects system locale.
    """
    configured = get_configured_language_setting()
    if configured in ("es", "en"):
        return configured

    # Auto-detect from system locale
    try:
        sys_loc = QLocale.system().name().lower()
        if sys_loc.startswith("es"):
            return "es"
    except Exception:
        pass
    return "en"


def get_available_languages() -> Dict[str, str]:
    """Returns available language choices for UI selectors."""
    return {
        "auto": t("app.lang_auto"),
        "es": t("app.lang_es"),
        "en": t("app.lang_en"),
    }


def t(key: str, **kwargs: Any) -> str:
    """
    Translates a key according to the active language.
    Falls back to Spanish if key is missing in English, or returns key if not found.
    Interpolates any **kwargs into formatted string.
    """
    lang = resolve_active_language()
    catalog = TRANSLATIONS.get(lang, TRANSLATIONS["en"])

    text = catalog.get(key)
    if text is None:
        # Fallback to English or Spanish
        text = TRANSLATIONS["en"].get(key, TRANSLATIONS["es"].get(key, key))

    if kwargs:
        try:
            return text.format(**kwargs)
        except Exception:
            return text
    return text
